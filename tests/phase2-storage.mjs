import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir,mkdtemp,readFile,rename,writeFile,symlink,rm } from 'node:fs/promises';
import { resolve,dirname } from 'node:path';
import { openStorage } from '../apps/transfer-agent/storage.mjs';
import { day,iso,sha } from '../apps/phase2/common.mjs';
import { samplePdf } from '../scripts/fixture.mjs';

const base=resolve('.local/test-storage');
await mkdir(base,{recursive:true});
const root=await mkdtemp(base+'/run-');
let now=Date.parse('2026-11-24T00:00:00Z');
const bytes=samplePdf(), id=randomUUID(), requestId='offline-delete';
let storage=await openStorage(root,()=>now);
try {
  const saved=await storage.save({documentId:id,requestId,filename:'0100111120261124a01.pdf',fileHash:sha(bytes),documentCode:'G001',
    patientKey:'synthetic-hmac',birthVerify:'synthetic-hmac',createdAt:iso(now)},bytes);
  const path=resolve(root,saved.local_path);
  assert.equal(sha(await readFile(path)),sha(bytes));
  assert.ok(path.endsWith(id+'.pdf'));
  assert.throws(()=>storage.setPolicy(id,{documentId:id,retentionDays:91,validityDays:91}),/POLICY_SYNC_FAILED/);
  storage.setPolicy(id,{documentId:id,retentionDays:1,validityDays:1,policyVersion:1,registeredAt:iso(now),expiresAt:iso(now+day),deleteAt:iso(now+day)});
  storage.ready(id);
  storage.db.close();
  storage=await openStorage(root,()=>now);
  await storage.recover();
  assert.equal(storage.get(requestId).state,'READY');
  const status=await storage.metrics();
  assert.equal(status.count,1);
  assert.equal(status.bytes,bytes.length);
  assert.equal(status.warning,status.utilization>=80);
  const altered=Buffer.from(bytes);
  altered[16]^=1;
  await writeFile(path,altered);
  await assert.rejects(storage.handle(id,new AbortController()),/FILE_HASH_MISMATCH/);
  await writeFile(path,bytes);
  const outside=resolve(root,'outside');
  await mkdir(outside);
  await writeFile(resolve(outside,id+'.pdf'),bytes);
  storage.db.prepare("UPDATE document SET local_path=? WHERE document_id=?").run('../outside/'+id+'.pdf',id);
  await assert.rejects(storage.handle(id,new AbortController()),/UNSAFE_STORAGE/);
  storage.db.prepare("UPDATE document SET local_path=? WHERE document_id=?").run(saved.local_path,id);
  const folder=dirname(path);
  const backup=folder+'-backup';
  await rename(folder,backup);
  await symlink(outside,folder,'junction');
  await assert.rejects(storage.handle(id,new AbortController()),/UNSAFE_STORAGE/);
  now+=day;
  assert.equal(await storage.purge(),1);
  assert.equal(storage.get(requestId).state,'DELETE_FAILED');
  assert.equal(storage.pending().length,1);
  assert.ok(await readFile(resolve(outside,id+'.pdf')));
  await rm(folder);
  await rename(backup,folder);
  await assert.rejects(storage.handle(id,new AbortController()),/LINK_UNAVAILABLE/);
  assert.equal(await storage.purge(),1);
  assert.equal(storage.get(requestId).state,'DELETED');
  assert.equal(storage.get(requestId).original_filename,null);
  assert.equal(storage.pending().length,1);
  await assert.rejects(readFile(path),/ENOENT/);
  storage.synced(id);
  assert.equal(storage.pending().length,0);
  console.log('SQLite durable index, exact expiry, path containment, offline deletion, failed deletion retry and disk metric passed');
} finally {storage.db.close();}
