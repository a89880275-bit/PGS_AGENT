import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {requireLocal} from '../apps/phase2/common.mjs';
const {chromium}=requireLocal('playwright-core','PGS_BROWSER_MODULES');
const origin='https://127.0.0.1:'+(process.env.PGS_PORT??4195);
const agentOrigin='http://127.0.0.1:'+(process.env.PGS_AGENT_PORT??4196);
const screenshots=process.env.PGS_SCREENSHOTS;
if(screenshots)await mkdir(screenshots,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.PGS_BROWSER_EXE,args:['--disable-background-networking']});
const desktop=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:960}});
const mobile=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:320,height:800},isMobile:true,hasTouch:true});
for(const context of [desktop,mobile]){
  context.setDefaultTimeout(15000);
  await context.route('**/*',route=>[origin,agentOrigin,'blob:'].some(base=>route.request().url().startsWith(base==='blob:'?base:base+'/'))?route.continue():route.abort());
}
const agent=await desktop.newPage(), admin=await desktop.newPage(), patient=await mobile.newPage();
const errors=[];
for(const page of [agent,admin,patient])page.on('pageerror',error=>errors.push(error.message));
const button=(page,name)=>page.getByRole('button',{name,exact:true});
const heading=(page,name)=>page.getByRole('heading',{name,exact:true}).waitFor();
const link=(page,name)=>page.getByRole('link',{name,exact:true});
const save=async(page,file)=>{if(screenshots)await page.screenshot({path:resolve(screenshots,file),fullPage:true});};
try{
  await agent.goto(origin+'/agent#manual');
  await heading(agent,'합성 PDF 수동 등록');
  const response=await fetch(agentOrigin+'/mock/sample');
  await agent.getByLabel('테스트 PDF 선택').setInputFiles({name:'0100111120261124a01.pdf',mimeType:'application/pdf',buffer:Buffer.from(await response.arrayBuffer())});
  await button(agent,'파일명 분석 및 환자 확인').click();
  await agent.getByText('1 / 2',{exact:true}).waitFor();
  assert.equal(await agent.getByText('19550203',{exact:true}).count(),0);
  await button(agent,'내부 저장 및 등록').click();
  const issued=await link(agent,'환자 시연 링크 열기').getAttribute('href');
  assert.match(issued,/\/g\//);
  const requestId=await agent.locator('section.panel').filter({has:agent.getByRole('heading',{name:'요청 처리',exact:true})}).locator('p.path').first().innerText();
  await save(agent,'agent-issued.png');
  await patient.goto(issued);
  const birth=patient.getByLabel('생년월일');
  assert.equal(await birth.getAttribute('inputmode'),'numeric');
  assert.equal(await patient.getByText('외래 안내문',{exact:true}).count(),0);
  await save(patient,'patient-verify.png');
  await birth.fill('19550204');
  await button(patient,'확인').click();
  await patient.getByRole('alert').waitFor();
  await birth.fill('19550203');
  await button(patient,'확인').click();
  await heading(patient,'외래 안내문');
  assert.equal(new URL(patient.url()).pathname,'/patient/view');
  await patient.getByText('1 / 2',{exact:true}).waitFor();
  await button(patient,'다음').click();
  await patient.getByText('2 / 2',{exact:true}).waitFor();
  await button(patient,'확대').click();
  await patient.getByText('125%',{exact:true}).waitFor();
  assert.equal(await patient.evaluate(()=>document.documentElement.scrollWidth),320);
  const download=patient.waitForEvent('download');
  await link(patient,'PDF 다운로드').click();
  assert.equal((await download).suggestedFilename(),'pgs-guide.pdf');
  await save(patient,'patient-pdf.png');
  await button(patient,'조회 종료').click();
  await heading(patient,'받은 링크를 열어 주세요');
  await patient.goto(origin+'/patient/view');
  await heading(patient,'확인 시간이 끝났어요');
  await admin.goto(origin+'/admin#settings');
  await heading(admin,'환자 인증 및 세션');
  await save(admin,'admin-security.png');
  await link(admin,'안내문 관리').click();
  const row=admin.getByRole('row').filter({hasText:requestId});
  assert.equal(await row.locator('a[href*="/g/"]').count(),0);
  await row.getByRole('button',{name:'링크 확인',exact:true}).click();
  assert.equal(await link(admin,'보안 링크 열기').getAttribute('href'),issued);
  assert.deepEqual(errors,[]);
  console.log('Phase 3 Edge UI passed: registration, authentication, 320px PDF, download and logout');
}finally{await browser.close();}
